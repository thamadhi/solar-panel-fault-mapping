from typing import Any, Dict, List, Optional, Tuple
import numpy as np


class LocalisationAnalysisResult:
    """
    Stores the results generated by the fault localisation handler.

    Separate from AnalysisResult (used by detection) because localization
    needs additional fields: location string, bounding box coordinates,
    per-string probabilities, and reliability flag.
    """

    def __init__(
        self,
        result: str,
        location: Optional[str] = None,
        reading_confidence: float = 0.0,
        image_confidence: float = 0.0,
        result_images: Optional[List] = None,
        result_readings: Optional[List] = None,
        details: Optional[Dict[str, Any]] = None,
    ) -> None:
        """
        Args:
            result             : Human-readable fault description
                                 e.g. "Hotspot", "String Break", "Normal"
            location           : Human-readable location string
                                 e.g. "panel_3_in_string_2" or "Strings: [4, 6]"
            reading_confidence : Confidence from electrical model (0.0 - 1.0)
            image_confidence   : Confidence from image model (0.0 - 1.0)
            result_images      : List of BGR numpy arrays for display
                                 [annotated_image, overlay_image] for hotspot
            result_readings    : List of faulty string numbers for electrical
                                 e.g. [4, 6, 8]
            details            : Extra fields that vary by source:

                                 For image localization:
                                   bounding_box   : (x, y, w, h) or None
                                   is_hotspot     : bool

                                 For electrical localization:
                                   faulty_strings  : List[int]
                                   string_reliable : bool
                                   fault_type_code : int (0-5)
                                   threshold_used  : float
                                   per_row_results : List[Dict]
        """
        self.__result = result
        self.__location = location
        self.__reading_confidence = reading_confidence
        self.__image_confidence = image_confidence
        self.__result_images = result_images or []
        self.__result_readings = result_readings or []
        self.__details = details or {}

    @property
    def result(self) -> str:
        return self.__result

    @property
    def location(self) -> Optional[str]:
        return self.__location

    @property
    def reading_confidence(self) -> float:
        return self.__reading_confidence

    @property
    def image_confidence(self) -> float:
        return self.__image_confidence

    @property
    def result_images(self) -> List:
        return self.__result_images

    @property
    def result_readings(self) -> List:
        return self.__result_readings

    @property
    def details(self) -> Dict[str, Any]:
        return self.__details
