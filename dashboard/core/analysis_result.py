class AnalysisResult:
    """
    Stores the results generated by a fault analysis component.
    """

    def __init__(
            self,
            result: str,
            reading_confidence: float = 0.0,
            image_confidence: float = 0.0,
            result_images = None,
            result_readings = None
    ) -> None:
        """
        Initialize an AnalysisResult instance
        
        result : str
            Human-readable result description
        reading_confidence : float
            Confidence level from electrical readings
        image_confidence : float
            Confidence level from hotspot images

        result_images : list
            Output image related to the analysis
        result_readings : list
            Output readings related to the analysis
        """
        
        self.result = result
        self.reading_confidence = reading_confidence
        self.image_confidence = image_confidence
        self.result_images = result_images or []
        self.result_readings = result_readings or []
